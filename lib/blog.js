export const getPost = (slug) => POSTS.find((p) => p.slug === slug) || null;
export const postOg = (p) => og(p.short || p.title, 'The Nibble blog', p.theme || 'mint');

// plain text of a post (reading time, RSS)
const strip = (t) => String(t).replace(/\*\*/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
export function postText(p) {
  const out = [];
  for (const b of p.blocks) {
    if (b[0] === 'p' || b[0] === 'h2' || b[0] === 'h3' || b[0] === 'tip') out.push(strip(b[1]));
    else if (b[0] === 'ul' || b[0] === 'ol') out.push(...b[1].map(strip));
    else if (b[0] === 'qa') for (const [q, a] of b[1]) out.push(strip(q), strip(a));
  }
  return out.join('\n');
}
export const readingMinutes = (p) => Math.max(2, Math.round(postText(p).split(/\s+/).length / 220));
export const headingId = (t) => strip(t).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
